#!/bin/sh
# bf-network captive DNS: preserve real DNS answers for ordinary sites.
# Pre-auth access is still controlled by the HP5130 ACL. This resolver is
# reached only through the existing per-client DNS DNAT rules.
set -eu

PORTAL_IP="${PORTAL_IP:?PORTAL_IP required}"
HIJACK_DNS_IP="${HIJACK_DNS_IP:?HIJACK_DNS_IP required}"

# Only dedicated OS captive-detection hostnames are redirected to the portal.
# Do NOT include generic browsing domains (www.google.com, www.apple.com,
# www.gstatic.com, play.googleapis.com etc.): Windows may cache their fake IP.
DEFAULT_PROBES='captive.apple.com,connectivitycheck.gstatic.com,connectivitycheck.android.com,clients3.google.com,www.msftconnecttest.com,msftconnecttest.com,ipv6.msftconnecttest.com,msftncsi.com,www.msftncsi.com,detectportal.firefox.com,nmcheck.gnome.org,network-test.debian.org,connectivity-check.ubuntu.com,connect.rom.miui.com'
PROBE_DOMAINS="${CAPTIVE_DNS_PROBE_HOSTS:-$DEFAULT_PROBES}"

# Keep the existing optional Microsoft sign-in relay behaviour; when enabled,
# those login domains deliberately resolve to HIJACK_DNS_IP for the SNI relay.
PREAUTH_MS_DOMAINS="${PREAUTH_ALLOWED_SNI:-microsoft.com,login.microsoftonline.com,login.microsoft.com,login.windows.net,login.live.com,login.microsoftonline-p.com,account.activedirectory.windowsazure.com,accounts.accesscontrol.windows.net,autologon.microsoftazuread-sso.com,secure.aadcdn.microsoftonline-p.com,msauth.net,msauthimages.net,msftauth.net,msftauthimages.net,phonefactor.net}"
preauth_enabled=0
case "${PREAUTH_HTTPS_RELAY_ENABLED:-auto}" in
  1|true|yes|on) preauth_enabled=1 ;;
  auto) [ -n "${DOMAIN_AUTH_PROVIDERS:-}" ] && preauth_enabled=1 ;;
esac

# PORTAL_IP is also the Pi-hole DNS address in this deployment. Do NOT
# forward to HIJACK_DNS_IP: that would cause a self-referential DNS loop.
cat > /tmp/hijack.conf <<EOF
# Selective captive DNS (generated by dnsmasq/entrypoint.sh)
listen-address=${HIJACK_DNS_IP}
bind-interfaces
no-resolv
server=${PORTAL_IP}
# Never hold a second cache of these DNS answers; Pi-hole handles caching.
cache-size=0
local-ttl=0
EOF

# Reject configuration injection: only DNS names may be inserted in dnsmasq.
add_domain_mapping() {
  domain="$1"; address="$2"
  domain="$(printf '%s' "$domain" | tr '[:upper:]' '[:lower:]' | sed 's/^[[:space:]]*//;s/[[:space:]]*$//;s/^\*\.//')"
  [ -n "$domain" ] || return 0
  case "$domain" in
    *[!a-z0-9.-]*|.*|*..*|*.)
      echo "Invalid DNS hostname in captive list: $domain" >&2
      exit 1
      ;;
  esac
  printf 'address=/%s/%s\n' "$domain" "$address" >> /tmp/hijack.conf
}

# Pipeline subshell exit status is not portable to the caller in /bin/sh, so
# generate a list first, then parse it using a redirect to keep errors fatal.
printf '%s\n' "$PROBE_DOMAINS" | tr ',;' '\n\n' > /tmp/captive-probe-domains.txt
while IFS= read -r domain; do
  add_domain_mapping "$domain" "$PORTAL_IP"
done < /tmp/captive-probe-domains.txt

if [ "$preauth_enabled" = "1" ]; then
  printf '%s\n' "$PREAUTH_MS_DOMAINS" | tr ',;' '\n\n' > /tmp/captive-ms-domains.txt
  while IFS= read -r domain; do
    add_domain_mapping "$domain" "$HIJACK_DNS_IP"
  done < /tmp/captive-ms-domains.txt
fi

cat >> /tmp/hijack.conf <<EOF
log-queries
log-facility=/var/log/dnsmasq-hijack.log
EOF

# Important: never add a wildcard domain-to-portal mapping here.
exec dnsmasq -k --conf-file=/tmp/hijack.conf "$@"
